export const dict: Record<Lang, Record<DictKey, string>> = { en, te }

export function translate(lang: Lang, key: DictKey, vars?: Record<string, string | number>): string {
  let s = dict[lang][key] ?? dict.en[key] ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
  return s
}

// ---- formatting helpers ----------------------------------------------------

const inr0 = new Intl.NumberFormat('en-IN', { maximumFractionDigits: 0 })
const num1 = new Intl.NumberFormat('en-IN', { maximumFractionDigits: 1 })

export function rupees(v: number | null | undefined): string {
  if (v === null || v === undefined || Number.isNaN(v)) return '—'
  return `₹${inr0.format(Math.round(v))}`
}

export function fmtNum(v: number | null | undefined, digits = 0): string {
  if (v === null || v === undefined || Number.isNaN(v)) return '—'
  return digits === 0 ? inr0.format(Math.round(v)) : num1.format(v)
}

export function pct(v: number | null | undefined, signed = true): string {
  if (v === null || v === undefined || Number.isNaN(v)) return '—'
  const s = num1.format(Math.abs(v))
  if (!signed) return `${s}%`
  return `${v > 0 ? '+' : v < 0 ? '−' : ''}${s}%`
}

const TE_MONTHS = ['జనవరి', 'ఫిబ్రవరి', 'మార్చి', 'ఏప్రిల్', 'మే', 'జూన్', 'జూలై', 'ఆగస్టు', 'సెప్టెంబర్', 'అక్టోబర్', 'నవంబర్', 'డిసెంబర్']
const EN_MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']

/** "2026-11-03" → "3 Nov 2026" / "3 నవంబర్ 2026" (no timezone shifts). */
export function fmtDate(iso: string | null | undefined, lang: Lang, withYear = true): string {
  if (!iso) return '—'
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(iso)
  if (!m) return iso
  const [, y, mo, d] = m
  const month = (lang === 'te' ? TE_MONTHS : EN_MONTHS)[Number(mo) - 1]
  return `${Number(d)} ${month}${withYear ? ` ${y}` : ''}`
}

/** "₹1,500 to ₹2,000" / "₹1,500 నుండి ₹2,000 వరకు" */
export function rangeText(lang: Lang, lo: number | null | undefined, hi: number | null | undefined): string {
  return lang === 'te' ? `${rupees(lo)} నుండి ${rupees(hi)} వరకు` : `${rupees(lo)} to ${rupees(hi)}`
}

export function fmtDateTime(iso: string | null | undefined, lang: Lang): string {
  if (!iso) return '—'
  const dt = new Date(iso)
  if (Number.isNaN(dt.getTime())) return iso
  return dt.toLocaleString(lang === 'te' ? 'te-IN' : 'en-IN', { dateStyle: 'medium', timeStyle: 'short' })
}

export function shortDate(iso: string): string {
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(iso)
  if (!m) return iso
  return `${Number(m[3])} ${EN_MONTHS[Number(m[2]) - 1]}`
}
